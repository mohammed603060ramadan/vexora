BEGIN;

-- Keep the course creation form compatible with the existing Academy UI.
ALTER TABLE public.courses
  ADD COLUMN IF NOT EXISTS cover_image_url TEXT,
  ADD COLUMN IF NOT EXISTS promo_video_url TEXT;

-- The student workspace already supports a "Ready for review" state.
-- Allow that state in the database without changing existing task records.
ALTER TABLE public.tasks
  DROP CONSTRAINT IF EXISTS tasks_status_check;

ALTER TABLE public.tasks
  ADD CONSTRAINT tasks_status_check
  CHECK (status = ANY (ARRAY[
    'todo'::text,
    'in_progress'::text,
    'review'::text,
    'completed'::text,
    'blocked'::text
  ]));

-- Contracts are currently exposed as a read-only admin register.
CREATE TABLE IF NOT EXISTS public.contracts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  contract_number TEXT UNIQUE,
  title TEXT,
  name TEXT,
  status TEXT NOT NULL DEFAULT 'draft',
  currency CHAR(3) NOT NULL DEFAULT 'EGP',
  total_amount NUMERIC(14, 2),
  amount NUMERIC(14, 2),
  start_date DATE,
  end_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  client_id UUID REFERENCES public.clients(id) ON DELETE SET NULL,
  project_id UUID REFERENCES public.projects(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS contracts_created_at_idx
  ON public.contracts (created_at DESC);

CREATE INDEX IF NOT EXISTS contracts_status_idx
  ON public.contracts (status);

ALTER TABLE public.contracts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS contracts_admin_read ON public.contracts;
CREATE POLICY contracts_admin_read
  ON public.contracts
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.jwt()) -> 'app_metadata' ->> 'role' = 'admin');

GRANT SELECT ON public.contracts TO authenticated;
GRANT ALL ON public.contracts TO service_role;

-- Quotations are also exposed as a read-only admin register.
CREATE TABLE IF NOT EXISTS public.quotations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  quotation_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title TEXT,
  status TEXT NOT NULL DEFAULT 'draft',
  currency CHAR(3) NOT NULL DEFAULT 'EGP',
  total_amount NUMERIC(14, 2),
  amount NUMERIC(14, 2),
  valid_until DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  client_id UUID REFERENCES public.clients(id) ON DELETE SET NULL,
  request_id UUID REFERENCES public.project_requests(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS quotations_created_at_idx
  ON public.quotations (created_at DESC);

CREATE INDEX IF NOT EXISTS quotations_status_idx
  ON public.quotations (status);

ALTER TABLE public.quotations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS quotations_admin_read ON public.quotations;
CREATE POLICY quotations_admin_read
  ON public.quotations
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.jwt()) -> 'app_metadata' ->> 'role' = 'admin');

GRANT SELECT ON public.quotations TO authenticated;
GRANT ALL ON public.quotations TO service_role;

NOTIFY pgrst, 'reload schema';

COMMIT;
