-- The trigger function now respects internal account types instead of creating
-- a client record for every newly invited employee, manager, or administrator.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_name text;
  v_account_type text;
BEGIN
  v_name := COALESCE(
    NULLIF(trim(NEW.raw_user_meta_data ->> 'full_name'), ''),
    NULLIF(split_part(COALESCE(NEW.email, ''), '@', 1), ''),
    'New client'
  );

  -- Public sign-up metadata is user-editable. Only the student self-selection
  -- is used here for routing; internal roles are assigned by the admin API
  -- through app_metadata and a service-role profile update after invitation.
  v_account_type := CASE
    WHEN NEW.raw_user_meta_data ->> 'account_type' = 'student' THEN 'student'
    ELSE 'client'
  END;

  INSERT INTO public.profiles (id, full_name, account_type)
  VALUES (
    NEW.id,
    NULLIF(trim(NEW.raw_user_meta_data ->> 'full_name'), ''),
    v_account_type
  )
  ON CONFLICT (id) DO NOTHING;

  IF v_account_type IN ('client', 'student') THEN
    INSERT INTO public.clients (name, email, auth_user_id)
    VALUES (v_name, NEW.email, NEW.id)
    ON CONFLICT (auth_user_id)
    WHERE auth_user_id IS NOT NULL
    DO NOTHING;
  END IF;

  RETURN NEW;
END;
$function$;

